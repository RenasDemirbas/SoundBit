//! The MCP server object.

// `#[tool_handler]` generates async trait methods without `.await`.
#![allow(clippy::unused_async_trait_impl)]

use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, MutexGuard, PoisonError};

use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::model::{Implementation, ServerCapabilities, ServerConfig};
use rmcp::{ServerHandler, tool_handler};
use soundbit_app::model::Song;
use soundbit_app::{Session, SharedSession};

use crate::workspace::Workspace;
use crate::{ServeError, guide, tools};

/// How to start the server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServerOptions {
    /// Directory the agent may read projects from and write projects and exports to.
    pub root: PathBuf,
    /// Project to open at start-up; a new empty song otherwise.
    pub open: Option<PathBuf>,
}

/// Shared state behind every tool call.
#[derive(Debug)]
pub(crate) struct State {
    pub(crate) session: SharedSession,
    pub(crate) workspace: Workspace,
}

/// SoundBit as an MCP server: one editing session plus a sandboxed workspace.
#[derive(Debug, Clone)]
pub struct SoundBitServer {
    state: Arc<State>,
    tool_router: ToolRouter<Self>,
}

impl SoundBitServer {
    /// Creates the server.
    ///
    /// # Errors
    ///
    /// Returns [`ServeError::Workspace`] if `root` is not an accessible directory and
    /// [`ServeError::Open`] if the initial project cannot be opened.
    pub fn new(options: ServerOptions) -> Result<Self, ServeError> {
        let session = match options.open {
            Some(path) => Session::open(path)?,
            None => Session::new(Song::new("Untitled")),
        };
        Self::shared(Arc::new(Mutex::new(session)), &options.root)
    }

    /// Creates a server that edits an existing shared session, e.g. the one open in the GUI.
    ///
    /// # Errors
    ///
    /// Returns [`ServeError::Workspace`] if `root` is not an accessible directory.
    pub fn shared(session: SharedSession, root: &Path) -> Result<Self, ServeError> {
        let workspace = Workspace::new(root).map_err(|source| ServeError::Workspace {
            path: root.to_owned(),
            source,
        })?;
        let state = State { session, workspace };
        Ok(Self {
            state: Arc::new(state),
            tool_router: tools::router(),
        })
    }

    /// Locks the session. A panic in another tool call cannot leave it half-changed (commands
    /// apply atomically), so a poisoned lock is safe to recover.
    pub(crate) fn session(&self) -> MutexGuard<'_, Session> {
        self.state
            .session
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
    }

    pub(crate) fn workspace(&self) -> &Workspace {
        &self.state.workspace
    }
}

#[tool_handler(router = self.tool_router)]
#[allow(
    clippy::unused_async,
    reason = "generated by rmcp's tool_handler macro"
)]
impl ServerHandler for SoundBitServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("soundbit", env!("CARGO_PKG_VERSION")))
            .with_instructions(guide::INSTRUCTIONS)
    }
}
